// Generates src/buildInfo.ts with a fresh build stamp.
// Runs automatically before `npm run dev` and `npm run build` (predev/prebuild).
// The stamp is displayed in the UI so a stale client can be spotted instantly.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const stamp = new Date().toISOString();
const id = `${Date.now().toString(36)}${Math.floor(Math.random() * 1e6).toString(36)}`;
const out = `// AUTO-GENERATED by scripts/gen-build-info.mjs — do not hand-edit.\nexport const BUILD_ID = '${id}';\nexport const BUILD_TIME = '${stamp}';\n`;
writeFileSync(join(root, 'src', 'buildInfo.ts'), out);
console.log(`[build-info] ${id} (${stamp})`);
